import CoreML
import UIKit

/// Is this photo AI-generated?  Two layers:
///  1. Labels inside the file (Content Credentials / C2PA, IPTC "digital source type", generator settings,
///     Software tags).  When present these are a statement by the tool that made the image, so they decide.
///  2. A detector network (Community Forensics ViT-S/16-384, Park & Owens, CVPR 2025, MIT) for unlabelled
///     files.  It is a likelihood, so the app only says "likely" and keeps a wide "can't tell" band.
struct Authenticity: Codable, Equatable {
    enum Verdict: String, Codable { case labelledAI, aiEdited, likelyAI, unclear, noSigns }

    var verdict: Verdict
    /// Detector probability, nil if it didn't run.
    var aiProbability: Double?
    /// What the file's own metadata says, if anything.
    var label: Provenance.Finding?
    /// Camera make/model from EXIF (context only: trivially faked or stripped).
    var camera: String?

    /// Detector thresholds.  Real photos that fooled it in testing scored up to ~0.92, so "likely AI" needs
    /// more than that; camera photos typically score < 0.05.
    static let likelyAI = 0.93
    static let noSigns = 0.15

    static func decide(label: Provenance.Finding?, p: Double?, camera: String?) -> Authenticity {
        let v: Verdict
        switch label?.kind {
        case .generated: v = .labelledAI
        case .edited: v = .aiEdited
        default:
            if let p { v = p >= likelyAI ? .likelyAI : (p <= noSigns ? .noSigns : .unclear) } else { v = .unclear }
        }
        return Authenticity(verdict: v, aiProbability: p, label: label, camera: camera)
    }

    var isAI: Bool { verdict == .labelledAI || verdict == .likelyAI }

    /// Plain-language reasons, most decisive first.
    var evidence: [String] {
        var out: [String] = []
        if let l = label {
            switch l.kind {
            case .generated: out.append("\(l.source) in the file say it was generated by \(l.tool ?? "an AI tool").")
            case .edited: out.append("\(l.source) in the file say it was edited with \(l.tool ?? "generative AI").")
            case .capture: out.append("\(l.source) in the file describe a camera capture\(l.tool.map { " (\($0))" } ?? ""). The signature isn't checked here.")
            }
        } else {
            out.append("No AI labels in the file. Many apps strip them, so this alone proves nothing.")
        }
        if let p = aiProbability {
            let pct = Int((p * 100).rounded())
            let reading = p >= Self.likelyAI ? "strong AI-generation traces" : (p <= Self.noSigns ? "no AI-generation traces" : "a mixed reading")
            out.append("The detector found \(reading) (\(pct)% AI-like).")
        }
        if let c = camera { out.append("Camera details present: \(c). Easy to add or remove, so only a hint.") }
        return out
    }
}

// MARK: - layer 1: labels in the file

enum Provenance {
    struct Finding: Codable, Equatable {
        enum Kind: String, Codable { case generated, edited, capture }
        var kind: Kind
        var tool: String?
        var source: String          // "Content Credentials", "IPTC metadata", ...
    }

    /// Generators that write their name into metadata, matched lowercase.  Kept to long, distinctive strings
    /// so they can't turn up by chance.
    private static let tools: [(match: String, name: String)] = [
        ("dall-e", "DALL·E"), ("dall\u{00B7}e", "DALL·E"), ("chatgpt", "ChatGPT"), ("openai", "OpenAI"),
        ("midjourney", "Midjourney"), ("adobe firefly", "Adobe Firefly"), ("stable diffusion", "Stable Diffusion"),
        ("stability ai", "Stability AI"), ("comfyui", "ComfyUI"), ("novelai", "NovelAI"), ("google imagen", "Google Imagen"),
        ("gemini", "Google Gemini"), ("image playground", "Apple Image Playground"), ("ideogram", "Ideogram"),
        ("leonardo.ai", "Leonardo.Ai"), ("black forest labs", "FLUX (Black Forest Labs)"), ("bing image creator", "Bing Image Creator"),
        ("microsoft designer", "Microsoft Designer"), ("imagined with ai", "Meta AI"), ("grok", "Grok"),
    ]

    static func read(_ data: Data) -> Finding? {
        let meta = metadataBytes(data)
        guard !meta.isEmpty else { return nil }
        let lower = Data(meta.map { ($0 >= 65 && $0 <= 90) ? $0 + 32 : $0 })
        func has(_ s: String, in d: Data) -> Bool { d.range(of: Data(s.utf8)) != nil }
        let c2pa = has("c2pa", in: lower) && has("jumb", in: lower)
        let source = c2pa ? "Content Credentials" : "Metadata"
        // a known AI tool's name decides on its own; any other generator name is only used for display
        let aiTool = tools.first { has($0.match, in: lower) }?.name
        let tool = aiTool ?? generator(meta)

        // IPTC digital source type, used both by C2PA manifests and plain XMP
        if has("digitalsourcetype/compositewithtrainedalgorithmicmedia", in: lower) {
            return Finding(kind: .edited, tool: tool, source: source)
        }
        if has("digitalsourcetype/trainedalgorithmicmedia", in: lower) {
            return Finding(kind: .generated, tool: tool, source: source)
        }
        // Stable Diffusion web UIs embed their generation settings in PNG text
        if has("steps:", in: lower) && has("sampler:", in: lower) && has("cfg scale:", in: lower) {
            return Finding(kind: .generated, tool: tool ?? "Stable Diffusion", source: "Generation settings")
        }
        if has("class_type", in: lower) && (has("ksampler", in: lower) || has("checkpointloader", in: lower)) {
            return Finding(kind: .generated, tool: "ComfyUI", source: "Generation settings")
        }
        if let aiTool {
            // a tool name in an editor's history usually means generative fill, not a whole generated image
            let editor = has("photoshop", in: lower) || has("lightroom", in: lower)
            return Finding(kind: editor ? .edited : .generated, tool: aiTool, source: source)
        }
        if c2pa && has("digitalsourcetype/digitalcapture", in: lower) {
            return Finding(kind: .capture, tool: tool, source: source)
        }
        return nil
    }

    /// The C2PA claim generator, e.g. "ChatGPT" or "Adobe_Firefly": the CBOR text after `claim_generator`
    /// (C2PA 1.x) or after `name` inside `claim_generator_info` (2.x).
    private static func generator(_ d: Data) -> String? {
        func text(at start: Data.Index) -> String? {
            var i = start
            guard i < d.endIndex else { return nil }
            let h = d[i]
            var len = 0
            if (0x60...0x77).contains(h) { len = Int(h - 0x60); i += 1 }
            else if h == 0x78, i + 1 < d.endIndex { len = Int(d[i + 1]); i += 2 }
            else { return nil }
            guard len > 1, i + len <= d.endIndex, let s = String(data: d[i..<(i + len)], encoding: .utf8) else { return nil }
            let name = (s.split(separator: "/").first.map(String.init) ?? s).replacingOccurrences(of: "_", with: " ")
            return name.isEmpty ? nil : name
        }
        var from = d.startIndex
        while let r = d.range(of: Data("claim_generator".utf8), in: from..<d.endIndex) {
            if let t = text(at: r.upperBound) { return t }
            // 2.x: claim_generator_info: [{ "name": "...", ... }]
            let window = r.upperBound..<min(d.endIndex, r.upperBound + 48)
            if let n = d.range(of: Data([0x64]) + Data("name".utf8), in: window), let t = text(at: n.upperBound) { return t }
            from = r.upperBound
        }
        return nil
    }

    /// Only the metadata parts of the file, so a name can't match by chance inside compressed pixel data.
    static func metadataBytes(_ d: Data) -> Data {
        let b = [UInt8](d)
        // JPEG: every APPn / COM segment before the image data
        if b.count > 4, b[0] == 0xFF, b[1] == 0xD8 {
            var out = Data()
            var i = 2
            while i + 4 <= b.count, b[i] == 0xFF {
                let marker = b[i + 1]
                if marker == 0xDA || marker == 0xD9 { break }
                let len = Int(b[i + 2]) << 8 | Int(b[i + 3])
                guard len >= 2, i + 2 + len <= b.count else { break }
                if (0xE0...0xEF).contains(marker) || marker == 0xFE { out.append(contentsOf: b[(i + 4)..<(i + 2 + len)]) }
                i += 2 + len
            }
            return out
        }
        // PNG: every chunk except the pixel data
        if b.count > 8, b[0] == 0x89, b[1] == 0x50, b[2] == 0x4E, b[3] == 0x47 {
            var out = Data()
            var i = 8
            while i + 8 <= b.count {
                let len = Int(b[i]) << 24 | Int(b[i + 1]) << 16 | Int(b[i + 2]) << 8 | Int(b[i + 3])
                let type = String(bytes: b[(i + 4)..<(i + 8)], encoding: .ascii) ?? ""
                guard len >= 0, i + 12 + len <= b.count else { break }
                if type != "IDAT" { out.append(contentsOf: type.utf8); out.append(contentsOf: b[(i + 8)..<(i + 8 + len)]) }
                if type == "IEND" { break }
                i += 12 + len
            }
            return out
        }
        // HEIC / WebP / others: metadata boxes sit near the start (C2PA sometimes at the end)
        let head = d.prefix(2 << 20)
        return d.count > (3 << 20) ? head + d.suffix(1 << 20) : d
    }
}

// MARK: - layer 2: the detector network

enum DetectorInput {
    static let crop = 384, resize = 440

    /// Shorter side to 440, centre 384 crop, RGB 0-255 in CHW order (the model normalises internally).
    /// Pixels stay in the file's own colour space, as in the PIL pipeline the model was trained with.
    static func make(_ ui: UIImage) throws -> MLMultiArray {
        let pw = ui.size.width * ui.scale, ph = ui.size.height * ui.scale
        let k = CGFloat(resize) / min(pw, ph)
        let w = max(crop, Int((pw * k).rounded())), h = max(crop, Int((ph * k).rounded()))
        let img = try ImagePrep.render(ui, width: w, height: h)
        let x0 = Int((Double(w - crop) / 2).rounded()), y0 = Int((Double(h - crop) / 2).rounded())
        let arr = try MLMultiArray(shape: [1, 3, NSNumber(value: crop), NSNumber(value: crop)], dataType: .float32)
        let p = arr.dataPointer.bindMemory(to: Float.self, capacity: 3 * crop * crop)
        let plane = crop * crop
        for y in 0..<crop {
            for x in 0..<crop {
                let s = ((y + y0) * w + x + x0) * 3, o = y * crop + x
                p[o] = Float(img.data[s]); p[plane + o] = Float(img.data[s + 1]); p[2 * plane + o] = Float(img.data[s + 2])
            }
        }
        return arr
    }
}
