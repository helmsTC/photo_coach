package com.mosaiclens.apertureiq.judge

import kotlinx.serialization.Serializable
import kotlin.math.max
import kotlin.math.min

/**
 * Is this photo AI-generated?  Two layers:
 *  1. Labels inside the file (Content Credentials / C2PA, IPTC "digital source type", generator settings,
 *     Software tags).  When present these are a statement by the tool that made the image, so they decide.
 *  2. A detector network (Community Forensics ViT-S/16-384, Park & Owens, CVPR 2025, MIT) for unlabelled
 *     files.  It is a likelihood, so the app only says "likely" and keeps a wide "can't tell" band.
 */
@Serializable
data class Authenticity(
    val verdict: Verdict,
    /** Detector probability, null if it didn't run. */
    val aiProbability: Double? = null,
    /** What the file's own metadata says, if anything. */
    val label: Provenance.Finding? = null,
    /** Camera make/model from EXIF (context only: trivially faked or stripped). */
    val camera: String? = null,
) {
    @Serializable
    enum class Verdict { labelledAI, aiEdited, likelyAI, unclear, noSigns }

    val isAI: Boolean get() = verdict == Verdict.labelledAI || verdict == Verdict.likelyAI

    /** Plain-language reasons, most decisive first. */
    val evidence: List<String>
        get() {
            val out = ArrayList<String>()
            val l = label
            if (l != null) {
                when (l.kind) {
                    Provenance.Kind.generated -> out.add("${l.source} in the file say it was generated by ${l.tool ?: "an AI tool"}.")
                    Provenance.Kind.edited -> out.add("${l.source} in the file say it was edited with ${l.tool ?: "generative AI"}.")
                    Provenance.Kind.capture -> out.add("${l.source} in the file describe a camera capture${l.tool?.let { " ($it)" } ?: ""}. The signature isn't checked here.")
                }
            } else {
                out.add("No AI labels in the file. Many apps strip them, so this alone proves nothing.")
            }
            val p = aiProbability
            if (p != null) {
                val pct = rndInt(p * 100)
                val reading = if (p >= likelyAI) "strong AI-generation traces" else if (p <= noSigns) "no AI-generation traces" else "a mixed reading"
                out.add("The detector found $reading ($pct% AI-like).")
            }
            camera?.let { out.add("Camera details present: $it. Easy to add or remove, so only a hint.") }
            return out
        }

    companion object {
        /**
         * Detector thresholds.  Real photos that fooled it in testing scored up to ~0.92, so "likely AI" needs
         * more than that; camera photos typically score < 0.05.
         */
        const val likelyAI = 0.93
        const val noSigns = 0.15

        fun decide(label: Provenance.Finding?, p: Double?, camera: String?): Authenticity {
            val v = when (label?.kind) {
                Provenance.Kind.generated -> Verdict.labelledAI
                Provenance.Kind.edited -> Verdict.aiEdited
                else -> if (p != null) (if (p >= likelyAI) Verdict.likelyAI else if (p <= noSigns) Verdict.noSigns else Verdict.unclear) else Verdict.unclear
            }
            return Authenticity(v, p, label, camera)
        }
    }
}

// ---- layer 1: labels in the file

object Provenance {
    @Serializable
    enum class Kind { generated, edited, capture }

    /** `source` is "Content Credentials", "Metadata", "Generation settings". */
    @Serializable
    data class Finding(val kind: Kind, val tool: String? = null, val source: String)

    /**
     * Generators that write their name into metadata, matched lowercase.  Kept to long, distinctive strings
     * so they can't turn up by chance.
     */
    private val tools = listOf(
        "dall-e" to "DALL·E", "dall·e" to "DALL·E", "chatgpt" to "ChatGPT", "openai" to "OpenAI",
        "midjourney" to "Midjourney", "adobe firefly" to "Adobe Firefly", "stable diffusion" to "Stable Diffusion",
        "stability ai" to "Stability AI", "comfyui" to "ComfyUI", "novelai" to "NovelAI", "google imagen" to "Google Imagen",
        "gemini" to "Google Gemini", "image playground" to "Apple Image Playground", "ideogram" to "Ideogram",
        "leonardo.ai" to "Leonardo.Ai", "black forest labs" to "FLUX (Black Forest Labs)", "bing image creator" to "Bing Image Creator",
        "microsoft designer" to "Microsoft Designer", "imagined with ai" to "Meta AI", "grok" to "Grok",
    )

    /** First index of `pat` in `d[from, to)`, or -1. */
    internal fun indexOf(d: ByteArray, pat: ByteArray, from: Int = 0, to: Int = d.size): Int {
        if (pat.isEmpty()) return from
        val last = to - pat.size
        val p0 = pat[0]
        var i = from
        while (i <= last) {
            if (d[i] == p0) {
                var k = 1
                while (k < pat.size && d[i + k] == pat[k]) k++
                if (k == pat.size) return i
            }
            i++
        }
        return -1
    }

    fun read(data: ByteArray): Finding? {
        val meta = metadataBytes(data)
        if (meta.isEmpty()) return null
        val lower = ByteArray(meta.size) { val b = meta[it]; if (b in 65..90) (b + 32).toByte() else b }
        fun has(s: String) = indexOf(lower, s.toByteArray(Charsets.UTF_8)) >= 0
        val c2pa = has("c2pa") && has("jumb")
        val source = if (c2pa) "Content Credentials" else "Metadata"
        // a known AI tool's name decides on its own; any other generator name is only used for display
        val aiTool = tools.firstOrNull { has(it.first) }?.second
        val tool = aiTool ?: generator(meta)

        // IPTC digital source type, used both by C2PA manifests and plain XMP
        if (has("digitalsourcetype/compositewithtrainedalgorithmicmedia")) return Finding(Kind.edited, tool, source)
        if (has("digitalsourcetype/trainedalgorithmicmedia")) return Finding(Kind.generated, tool, source)
        // Stable Diffusion web UIs embed their generation settings in PNG text
        if (has("steps:") && has("sampler:") && has("cfg scale:")) return Finding(Kind.generated, tool ?: "Stable Diffusion", "Generation settings")
        if (has("class_type") && (has("ksampler") || has("checkpointloader"))) return Finding(Kind.generated, "ComfyUI", "Generation settings")
        if (aiTool != null) {
            // a tool name in an editor's history usually means generative fill, not a whole generated image
            val editor = has("photoshop") || has("lightroom")
            return Finding(if (editor) Kind.edited else Kind.generated, aiTool, source)
        }
        if (c2pa && has("digitalsourcetype/digitalcapture")) return Finding(Kind.capture, tool, source)
        return null
    }

    /**
     * The C2PA claim generator, e.g. "ChatGPT" or "Adobe_Firefly": the CBOR text after `claim_generator`
     * (C2PA 1.x) or after `name` inside `claim_generator_info` (2.x).
     */
    private fun generator(d: ByteArray): String? {
        fun text(start: Int): String? {
            var i = start
            if (i >= d.size) return null
            val h = d[i].toInt() and 0xFF
            val len: Int
            if (h in 0x60..0x77) { len = h - 0x60; i += 1 }
            else if (h == 0x78 && i + 1 < d.size) { len = d[i + 1].toInt() and 0xFF; i += 2 }
            else return null
            if (len <= 1 || i + len > d.size) return null
            val bytes = d.copyOfRange(i, i + len)
            val s = try {
                Charsets.UTF_8.newDecoder().decode(java.nio.ByteBuffer.wrap(bytes)).toString()
            } catch (e: java.nio.charset.CharacterCodingException) {
                return null
            }
            val name = (s.split("/").firstOrNull { it.isNotEmpty() } ?: s).replace("_", " ")
            return name.ifEmpty { null }
        }
        val key = "claim_generator".toByteArray()
        val nameKey = byteArrayOf(0x64) + "name".toByteArray()
        var from = 0
        while (true) {
            val r = indexOf(d, key, from)
            if (r < 0) return null
            val end = r + key.size
            text(end)?.let { return it }
            // 2.x: claim_generator_info: [{ "name": "...", ... }]
            val n = indexOf(d, nameKey, end, min(d.size, end + 48))
            if (n >= 0) text(n + nameKey.size)?.let { return it }
            from = end
        }
    }

    /** Only the metadata parts of the file, so a name can't match by chance inside compressed pixel data. */
    fun metadataBytes(b: ByteArray): ByteArray {
        fun u(i: Int) = b[i].toInt() and 0xFF
        // JPEG: every APPn / COM segment before the image data
        if (b.size > 4 && u(0) == 0xFF && u(1) == 0xD8) {
            val out = java.io.ByteArrayOutputStream()
            var i = 2
            while (i + 4 <= b.size && u(i) == 0xFF) {
                val marker = u(i + 1)
                if (marker == 0xDA || marker == 0xD9) break
                val len = (u(i + 2) shl 8) or u(i + 3)
                if (len < 2 || i + 2 + len > b.size) break
                if (marker in 0xE0..0xEF || marker == 0xFE) out.write(b, i + 4, len - 2)
                i += 2 + len
            }
            return out.toByteArray()
        }
        // PNG: every chunk except the pixel data
        if (b.size > 8 && u(0) == 0x89 && u(1) == 0x50 && u(2) == 0x4E && u(3) == 0x47) {
            val out = java.io.ByteArrayOutputStream()
            var i = 8
            while (i + 8 <= b.size) {
                val len = (u(i) shl 24) or (u(i + 1) shl 16) or (u(i + 2) shl 8) or u(i + 3)
                val type = String(b, i + 4, 4, Charsets.US_ASCII)
                if (len < 0 || i + 12L + len > b.size) break
                if (type != "IDAT") { out.write(b, i + 4, 4); out.write(b, i + 8, len) }
                if (type == "IEND") break
                i += 12 + len
            }
            return out.toByteArray()
        }
        // HEIC / WebP / others: metadata boxes sit near the start (C2PA sometimes at the end)
        if (b.size > (3 shl 20)) return b.copyOfRange(0, 2 shl 20) + b.copyOfRange(b.size - (1 shl 20), b.size)
        return b
    }
}

// ---- layer 2: the detector network

object DetectorInput {
    const val crop = 384
    const val resize = 440

    /**
     * Shorter side to 440, centre 384 crop, RGB 0-255 in CHW order (the model normalises internally).
     * `full` is the decoded, upright photo; pixels stay in the file's own colour space, as in the PIL
     * pipeline the model was trained with.
     */
    fun make(full: RGBImage): FloatArray {
        val k = resize.toDouble() / min(full.width, full.height)
        val w = max(crop, rndInt(full.width * k)); val h = max(crop, rndInt(full.height * k))
        val img = if (w <= full.width && h <= full.height) ImagePrep.resizeArea(full, w, h) else Imaging.resizeBilinear(full, w, h)
        val x0 = rndInt((w - crop) / 2.0); val y0 = rndInt((h - crop) / 2.0)
        val plane = crop * crop
        val out = FloatArray(3 * plane)
        for (y in 0 until crop) {
            for (x in 0 until crop) {
                val s = ((y + y0) * w + x + x0) * 3; val o = y * crop + x
                out[o] = img.data.u(s).toFloat(); out[plane + o] = img.data.u(s + 1).toFloat(); out[2 * plane + o] = img.data.u(s + 2).toFloat()
            }
        }
        return out
    }
}
